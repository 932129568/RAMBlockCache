#!/usr/bin/env python3
"""Gate15 - repository layout contract.

Pure-static, CI-friendly. Enforces the normalized layout that came out of
report 140 (B1..B4). Checks:

  1. Root whitelist: only the agreed files/dirs at repo root.
  2. Forbidden dirs anywhere in the tracked tree:
     src/src, src/ui/wpf (legacy), bin/, obj/, build dirs outside build/,
     node_modules, x64 (outside src/driver/x64 which is untracked output).
     Actually: tracked files must not live under bin/obj/node_modules/x64 at all.
  3. No mojibake tracked paths. Legit UTF-8 Chinese doc names are fine
     (docs/00-总览.md etc.); what this gate bans is GBK-transcode damage:
     U+FFFD replacement chars, CJK codepoints that appear inside *code*
     directories (src/**/*.c|h|py|ps1), and the known damaged stems (寰, 幆).
  4. No *.obj/*.exe/*.pdb/*.dll tracked outside the signed deliverables in dist/
     (the distribution keeps exactly: RAMBlockCache.sys, .sha256, Setup exe).
  5. build/sources.manifest.json + build/build.ps1 + build/RAMBlockCache.sln exist.
  6. src/scripts/finalize_*.ps1 must not come back (one-off scripts live in
     archive/oneoff/).
  7. No duplicate README pairs: README.txt must not exist (merged into README.md
     in B3; the deploy anchors reference README.txt -> that file must be
     regenerated by sync_anchors, not tracked at root).

Exit 0 = PASS, 1 = FAIL.
"""
import subprocess
import sys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
fails = []

ROOT_WHITELIST = {
    ".git", ".github", ".gitignore", ".nuget", ".mimosa", ".workbuddy",
    ".workbuddy-ai", ".zcode",
    # [AGENTS.md 2026-11-11] 仓库根常驻工作协议（新会话入口 / 红线 / 交接规则）。
    # 它是**项目资产**而非临时文件：所有接手人（人和 agent）都从这里读规则。
    # 未跟踪状态是预期（仓库纪律"先不提交"），而本门禁遍历文件系统而非 git
    # 索引，故必须显式登记——否则本地 gates 会因它而误红（CI 干净 checkout
    # 时不存在该文件，两边结论本该一致）。
    "AGENTS.md",
    "KNOWN_ISSUES.md", "README.md",
    "archive", "build", "certs", "deliverables", "dist", "docs", "src",
    "tests", "tools",
}

FORBIDDEN_DIR_PARTS = {"node_modules", "obj", "bin", "x64", "Debug", "Release"}

def tracked_files():
    out = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files", "-z"],
        capture_output=True, check=True,
    ).stdout.decode("utf-8", errors="replace").split("\0")
    return [f for f in out if f]

# --- 1. root whitelist -------------------------------------------------------
for p in ROOT.iterdir():
    if p.name.startswith(".") and p.name not in ROOT_WHITELIST:
        continue  # untracked dot-dirs are host artifacts, not repo layout
    if p.name not in ROOT_WHITELIST:
        fails.append(f"root entry outside whitelist: {p.name}")

# --- 2-4. per tracked file ---------------------------------------------------
art_pat = re.compile(r"\.(obj|pdb|dll|lib|exp|ilk)$", re.IGNORECASE)
exe_allowed = {
    "dist/RAMBlockCache-Setup.exe",
    # Payload release inputs: build_setup.ps1 embeds these verbatim, and there
    # is no MSVC on CI to rebuild them - the tracked exe IS the deliverable.
    # They are rebuilt locally by build/build.ps1 -Target ctl|setup and guarded
    # by Gate9 (RB_STATS contract strings + freshness).
    "src/ctl/ramboostctl.exe",
    "src/ctl/rbfeatctl.exe",
    "src/setup/ramboostsetup.exe",
}
sys_allowed = {"dist/RAMBlockCache.sys", "dist/RAMBlockCache.sys.sha256"}

for f in tracked_files():
    parts = f.split("/")
    low = [p.lower() for p in parts]
    if any(seg in FORBIDDEN_DIR_PARTS for seg in low[:-1]):
        fails.append(f"tracked file under forbidden build dir: {f}")
    if "src" in low and "src/src" in "/".join(low):
        fails.append(f"tracked file under src/src: {f}")
    if low[0] == "src" and len(low) > 2 and low[1] == "ui" and low[2] == "wpf":
        fails.append(f"legacy WPF ressurected under src/ui/wpf: {f}")
    # mojibake: U+FFFD anywhere, known damaged stems anywhere, or any CJK
    # character inside a CODE path (code tree must stay ASCII; docs may be
    # Chinese). This is the check that would have caught the 寰幆 trio.
    if "\ufffd" in f or "寰" in f or "幆" in f:
        fails.append(f"mojibake tracked path: {f}")
    elif any("\u4e00" <= ch <= "\u9fff" for ch in f):
        code_exts = (".c", ".h", ".cpp", ".py", ".ps1", ".cmd", ".bat",
                     ".cs", ".csproj", ".vcxproj", ".json", ".yml", ".rc")
        low = f.lower()
        if low.endswith(code_exts):
            fails.append(f"non-ASCII name on code file: {f}")
        elif low.startswith("src/") or low.startswith("tests/"):
            fails.append(f"non-ASCII path inside code tree: {f}")
    # build artifacts in the tree
    if art_pat.search(f):
        fails.append(f"tracked build artifact: {f}")
    if f.endswith(".exe") and f not in exe_allowed:
        fails.append(f"tracked exe outside whitelist: {f}")
    if f.endswith(".sys") and f not in sys_allowed:
        fails.append(f"tracked sys outside whitelist: {f}")
    if f == "README.txt":
        fails.append("README.txt tracked at root (merge into README.md; "
                     "anchor copies are generated, not tracked)")
    if f.startswith("src/scripts/finalize_"):
        fails.append(f"one-off finalize script back in src/scripts: {f}")
    if f.startswith("outputs/") or f.startswith("report/"):
        fails.append(f"scratch dir tracked: {f}")

# --- 5. build triangle --------------------------------------------------------
for req in ("build/build.ps1", "build/sources.manifest.json", "build/RAMBlockCache.sln"):
    if not (ROOT / req).exists():
        fails.append(f"missing required build file: {req}")

print("== check_layout (Gate15) ==")
if fails:
    for x in fails:
        print(f"  [FAIL] {x}")
    print(f"GATE15 FAIL ({len(fails)} problem(s))")
    sys.exit(1)
print("GATE15 PASS")
